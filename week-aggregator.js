/**
 * Pure weekly-log and meal-history aggregation for the diary dashboards.
 *
 * The UMD module exposes a `createWeekAggregator` factory. The host injects
 * `resolveHistoricalGoals` from historical-goals-model.js and `formatDateDM`
 * from date-utils.js. Callers provide already parsed logs, local day numbers,
 * the fixed persisted meal keys, and an explicit goal-context snapshot. The
 * returned values are plain week rows or per-meal averages; this module never
 * reads storage, React state, the DOM, or the clock.
 *
 * Known behavior intentionally preserved by the host loaders: storage reads
 * remain sequential and uncancelled, concurrent runs may commit out of order,
 * invalid JSON rejects the whole loader, and the triggering effect omits
 * `profileData`, `currentWeight`, and `currentHeight` from its dependency list.
 * Meal analysis deliberately
 * does not normalize translated or legacy meal keys, so only the supplied
 * persisted PT keys are counted. Day numbers must be supplied by the host and
 * are not reconstructed from ISO dates because the existing local-Date plus
 * UTC-ISO conversion can disagree around timezone and DST boundaries.
 *
 * @module WeekAggregator
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  if (root) root.WeekAggregator = api;
})(typeof window !== "undefined" ? window : globalThis, function () {
  "use strict";

  const COVERAGE_NUTRIENTS = Object.freeze([
    "protein",
    "kcal",
    "carbs",
    "fat",
    "fiber",
    "salt"
  ]);

  function finiteNutrient(value) {
    if (value === null || value === undefined || value === "") return null;
    const number = Number(value);
    return Number.isFinite(number) && number >= 0 ? number : null;
  }

  function nutrientCoverage(entries, field) {
    const values = entries.map(entry => finiteNutrient(entry && entry[field]));
    const known = values.filter(value => value !== null);
    return {
      knownItemCount: known.length,
      missingItemCount: values.length - known.length,
      totalItemCount: values.length,
      complete: values.length > 0 && known.length === values.length
    };
  }

  /**
   * Creates the weekly aggregation API with domain dependencies supplied by the host.
   *
   * @param {Object} dependencies Injected dependencies.
   * @param {function(Object): Object} dependencies.resolveHistoricalGoals Resolves raw and effective goals for one date.
   * @param {function(string): string} dependencies.formatDateDM Formats a stored date as day-month.
   * @returns {Object} Weekly-row and meal-average aggregation helpers.
   */
  function createWeekAggregator({ resolveHistoricalGoals, formatDateDM }) {
    if (typeof resolveHistoricalGoals !== "function" || typeof formatDateDM !== "function") {
      throw new TypeError("WeekAggregator requires resolveHistoricalGoals and formatDateDM functions");
    }

    /**
     * Aggregates eight resolved diary logs into the exact rows consumed by weekly charts and metrics.
     *
     * @param {Object} snapshot Explicit aggregation input.
     * @param {Array<{date: string, day: number}>} snapshot.dayDescriptors Dates and original local day numbers generated by the host.
     * @param {Object<string, Object>} snapshot.logsByDate Parsed and week-normalized logs keyed by stored date.
     * @param {string} snapshot.today Current stored date.
     * @param {Object<string, boolean>} snapshot.trainingByDate Explicit training/rest choices by date.
     * @param {Object} snapshot.goalContext Goal-resolution state captured by the host.
     * @returns {Array<Object>} Weekly rows including historical and today-connection chart series.
     */
    function aggregateWeekRows({
      dayDescriptors,
      logsByDate,
      today,
      trainingByDate,
      goalContext
    }) {
      const days = [];
      dayDescriptors.forEach(({ date, day }) => {
        const dayLog = logsByDate[date] || {};
        const entries = Object.values(dayLog).flat();
        const dayIsTraining = trainingByDate[date] ?? true;
        const { rawGoal, effectiveGoal: g } = resolveHistoricalGoals({
          date,
          today,
          dayIsTraining,
          weightHistory: goalContext.weightHistory,
          currentWeight: goalContext.currentWeight,
          currentHeight: goalContext.currentHeight,
          profileData: goalContext.profileData,
          nutritionPrefs: goalContext.nutritionPrefs,
          customGoals: goalContext.customGoals,
          frozenGoal: goalContext.goalHistory[date]
        });
        const protein = entries.reduce((s, e) => s + (e.protein ?? 0), 0);
        const kcal = entries.reduce((s, e) => s + (e.kcal ?? 0), 0);
        const isTodayEntry = date === today;
        const proteinTrend = Math.round(protein);
        const kcalTrend = Math.round(kcal);
        const carbs = entries.reduce((s, e) => s + (e.carbs ?? 0), 0);
        const fat = entries.reduce((s, e) => s + (e.fat ?? 0), 0);
        const fiber = entries.reduce((s, e) => s + (e.fiber ?? 0), 0);
        const salt = entries.reduce((s, e) => s + (e.salt ?? 0), 0);
        const nutrientCoverageByField = Object.fromEntries(
          COVERAGE_NUTRIENTS.map(field => [field, nutrientCoverage(entries, field)])
        );
        days.push({
          date,
          label: formatDateDM(date),
          day,
          protein: Math.round(protein),
          proteinTrend,
          proteinPastLine: isTodayEntry ? null : proteinTrend,
          proteinTodayLine: null,
          kcal: Math.round(kcal),
          kcalTrend,
          kcalPastLine: isTodayEntry ? null : kcalTrend,
          kcalTodayLine: null,
          carbs: Math.round(carbs),
          fat: Math.round(fat),
          fiber: Math.round(fiber),
          salt: Math.round(salt * 10) / 10,
          carbsGoal: g.carbs,
          fatGoal: g.fat,
          fiberGoal: g.fiber,
          saltGoal: g.salt,
          proteinGoal: g.protein,
          kcalGoal: g.kcal,
          baseCalories: rawGoal.baseCalories || g.kcal,
          adjustment: rawGoal.adjustment || 0,
          metProtein: protein >= g.protein,
          metKcal: kcal >= g.kcal * 0.85 && kcal <= g.kcal * 1.15,
          nutrientCoverage: nutrientCoverageByField,
          hasData: entries.length > 0,
          isToday: isTodayEntry
        });
      });

      const todayIdx = days.findIndex(day => day.isToday);
      if (todayIdx > 0) {
        days[todayIdx - 1].proteinTodayLine = days[todayIdx - 1].proteinTrend;
        days[todayIdx].proteinTodayLine = days[todayIdx].proteinTrend;
        days[todayIdx - 1].kcalTodayLine = days[todayIdx - 1].kcalTrend;
        days[todayIdx].kcalTodayLine = days[todayIdx].kcalTrend;
      }
      return days;
    }

    /**
     * Calculates per-meal counts and rounded nutrient averages from parsed historical logs.
     *
     * @param {Object} snapshot Explicit meal-analysis input.
     * @param {Array<Object>} snapshot.dailyLogs Parsed logs for available prior days.
     * @param {Array<string>} snapshot.mealKeys Fixed persisted PT meal keys to recognize in order.
     * @returns {Object<string, {count: number, avgProtein: number, avgKcal: number, avgCarbs: number}>} Per-meal averages.
     */
    function aggregateMealAverages({ dailyLogs, mealKeys }) {
      const acc = {};
      dailyLogs.forEach(dayLog => {
        mealKeys.forEach(meal => {
          const entries = dayLog[meal] || [];
          if (!entries.length) return;
          if (!acc[meal]) acc[meal] = {
            count: 0,
            protein: 0,
            kcal: 0,
            carbs: 0
          };
          acc[meal].count++;
          acc[meal].protein += entries.reduce((s, e) => s + (e.protein ?? 0), 0);
          acc[meal].kcal += entries.reduce((s, e) => s + (e.kcal ?? 0), 0);
          acc[meal].carbs += entries.reduce((s, e) => s + (e.carbs ?? 0), 0);
        });
      });

      const avgs = {};
      Object.entries(acc).forEach(([meal, data]) => {
        avgs[meal] = {
          count: data.count,
          avgProtein: Math.round(data.protein / data.count),
          avgKcal: Math.round(data.kcal / data.count),
          avgCarbs: Math.round(data.carbs / data.count)
        };
      });
      return avgs;
    }

    return { aggregateWeekRows, aggregateMealAverages };
  }

  return { createWeekAggregator };
});
